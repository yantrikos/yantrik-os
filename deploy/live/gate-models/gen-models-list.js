// Writes (or with --check, verifies) models-list.conf from the allowlist in live_models.js.
//   node gen-models-list.js           rewrite models-list.conf
//   node gen-models-list.js --check   exit 1 if it differs from what live_models.js implies
// The Mind asks GET <base>/models before it will use a provider, and the gate has no upstream
// for that: it answers from a static list. Generating it from RULES means the list and the
// filter cannot drift (a model listed but refused, or allowed but not listed).
const fs = require('fs');
const path = require('path');

const src = fs.readFileSync(path.join(__dirname, 'live_models.js'), 'utf8');
const m = src.match(/const RULES = (\{[\s\S]*?\n\});/);
if (!m) { console.error('RULES not found in live_models.js'); process.exit(2); }
const RULES = new Function('return ' + m[1])();

// The path each provider's base URL ends in (see mind-env.sh); the list is at <base>/models.
const BASE = {
    'ollama-cloud': '/ollama-cloud/v1',
    'nanogpt': '/nanogpt/api/v1',
    'nim': '/nim/v1',
};

let out = `# GENERATED by gen-models-list.js from live_models.js's RULES; do not edit. setup-models.sh checks it.
# GET <base>/models for the Mind, which will not use a provider whose list it cannot read. Static:
# no upstream and no provider key, only the instance key and the models the filter allows.
`;
for (const p of Object.keys(RULES)) {
    if (!BASE[p]) { console.error('no base path for provider ' + p); process.exit(2); }
    const body = JSON.stringify({
        object: 'list',
        data: RULES[p].models.map((id) => ({ id, object: 'model', owned_by: 'live-gate' })),
    });
    out += `
location = ${BASE[p]}/models {
    if ($http_authorization != "Bearer @INSTANCE_KEY@") { return 401; }
    limit_except GET { deny all; }
    default_type application/json;
    return 200 '${body}';
}
`;
}

const file = path.join(__dirname, 'models-list.conf');
if (process.argv[2] === '--check') {
    let have = '';
    try { have = fs.readFileSync(file, 'utf8'); } catch (e) { /* missing counts as different */ }
    if (have !== out) { console.error('models-list.conf differs from live_models.js'); process.exit(1); }
    console.log('models-list.conf matches live_models.js');
} else {
    fs.writeFileSync(file, out);
}
